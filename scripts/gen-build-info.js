#!/usr/bin/env node
/**
 * 【构建指纹 · 永久规则】
 * 每次出 release 包前必须运行（release:android / release:ios 脚本已自动调用），
 * 把当前 git short SHA + 构建时间写入 src/config/buildInfo.ts。
 * App 启动时以 [BUILD] sha=... built=... 打印到 logcat(Android)/Xcode 控制台(iOS)，
 * 用于在目标设备上确证"跑的就是这次代码"，杜绝"改了没装/装了旧包"。
 *
 * 用法： node scripts/gen-build-info.js
 */
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

function shortSha() {
  try {
    return execSync('git rev-parse --short HEAD', { encoding: 'utf8' }).trim();
  } catch {
    return 'unknown';
  }
}

function dirty() {
  try {
    // 只看已跟踪文件的改动；未跟踪素材(assets/等)不应把正式包标成 dirty。
    const out = execSync('git status --porcelain --untracked-files=no', { encoding: 'utf8' }).trim();
    return out.length > 0;
  } catch {
    return false;
  }
}

const sha = shortSha();
const built = new Date().toISOString();
const isDirty = dirty();
const target = path.join(__dirname, '..', 'src', 'config', 'buildInfo.ts');

const content = `/**
 * ⚠️ AUTO-GENERATED by scripts/gen-build-info.js — 请勿手改。
 * 出包前由 release 脚本自动刷新；App 启动打印 [BUILD] 行用于设备侧验真。
 */
export const BUILD_SHA = '${sha}';
export const BUILD_TIME = '${built}';
export const BUILD_DIRTY = ${isDirty};

/** 单行指纹，供启动日志与验收证据直接引用。 */
export const BUILD_STAMP = \`[BUILD] sha=\${BUILD_SHA}\${BUILD_DIRTY ? '-dirty' : ''} built=\${BUILD_TIME}\`;
`;

fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, content, 'utf8');
console.log(`[gen-build-info] wrote ${path.relative(process.cwd(), target)} -> sha=${sha}${isDirty ? '-dirty' : ''} built=${built}`);
